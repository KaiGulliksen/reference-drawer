// Everything the frontend needs from the Rust side of the app.

import { convertFileSrc, invoke } from "@tauri-apps/api/core";

export interface ImageEntry {
  path: string;
  name: string;
  /** File size in bytes. */
  size: number;
  /** Last modified time in milliseconds since 1970. */
  modified: number;
  /** Size in pixels as displayed (after EXIF rotation); 0 if it couldn't be read. */
  width: number;
  height: number;
}

export interface ScanResult {
  /** The folder that was scanned. */
  folder: string;
  images: ImageEntry[];
  /** How many tagged images were found again under a new name or in a new place (their tags moved with them). */
  relinked: number;
}

/** A named folder of images, browsed on its own. Saved in the library database. */
export interface Workspace {
  id: number;
  name: string;
  path: string;
  /** Whether images in subfolders are included. */
  recursive: boolean;
}

/** Lists the images in a workspace's folder, and keeps tags with images that were renamed or moved. */
export function scanWorkspace(id: number): Promise<ScanResult> {
  return invoke<ScanResult>("scan_workspace", { id });
}

export const listWorkspaces = () => invoke<Workspace[]>("list_workspaces");

/** Adds a folder as a workspace, or returns the existing workspace for that folder. */
export const addWorkspace = (path: string) => invoke<Workspace>("add_workspace", { path });

export const renameWorkspace = (id: number, name: string) => invoke<Workspace>("rename_workspace", { id, name });

export const setWorkspaceRecursive = (id: number, recursive: boolean) =>
  invoke<Workspace>("set_workspace_recursive", { id, recursive });

export const setWorkspaceFolder = (id: number, path: string) => invoke<Workspace>("set_workspace_folder", { id, path });

/** Removes a workspace (and its tags) from the library. Its folder and images are not touched. */
export const removeWorkspace = (id: number) => invoke<void>("remove_workspace", { id });

export interface Tag {
  id: number;
  name: string;
}

/** Every tag in a workspace, and which tags each tagged image has. */
export interface TagData {
  tags: Tag[];
  images: { path: string; tags: number[] }[];
}

export const getTags = (workspaceId: number) => invoke<TagData>("get_tags", { workspaceId });

/** Adds a tag (by name, created if new) to images. Returns the tag. */
export const addTag = (workspaceId: number, paths: string[], name: string) =>
  invoke<Tag>("add_tag", { workspaceId, paths, name });

/** Removes a tag from images. Resolves to true if the tag is now unused and was deleted. */
export const removeTag = (workspaceId: number, paths: string[], tagId: number) =>
  invoke<boolean>("remove_tag", { workspaceId, paths, tagId });

/** Renames a tag (merging it into another tag if that name is taken). */
export const renameTag = (workspaceId: number, tagId: number, name: string) =>
  invoke<TagData>("rename_tag", { workspaceId, tagId, name });

export const deleteTag = (workspaceId: number, tagId: number) => invoke<void>("delete_tag", { workspaceId, tagId });

/** URL of the small cached thumbnail for an image, generated by Rust on first request. */
export function thumbUrl(image: ImageEntry): string {
  // Including the modified time makes the webview fetch a fresh thumbnail after the file is edited.
  return `${convertFileSrc(image.path, "thumb")}?m=${image.modified}`;
}

/** URL of the original, full-size image file. */
export function fullUrl(image: ImageEntry): string {
  return convertFileSrc(image.path);
}

/** Preview sizes the Rust side can make (longest side, in pixels). Must match `PREVIEW_SIZES` in thumbs.rs. */
const PREVIEW_SIZES = [1920, 2560, 3840];

/** The smallest preview size that still covers the whole screen at full sharpness. */
export function previewSizeForScreen(): number {
  const screenPixels = Math.max(screen.width, screen.height) * (window.devicePixelRatio || 1);
  return PREVIEW_SIZES.find((size) => size >= screenPixels) ?? PREVIEW_SIZES[PREVIEW_SIZES.length - 1];
}

/**
 * URL of a screen-sized version of an image, used by the viewer instead of very large originals.
 * Images that already fit (and animated GIFs) are served unchanged.
 */
export function previewUrl(image: ImageEntry, size: number): string {
  return `${convertFileSrc(image.path, "thumb")}?m=${image.modified}&s=${size}`;
}

/** The real pixel size of an image (after EXIF rotation), read without decoding it. */
export function imageSize(path: string): Promise<{ width: number; height: number }> {
  return invoke("image_size", { path });
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
